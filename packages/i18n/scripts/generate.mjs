// Compiles locales/<locale>/<namespace>.ftl into src/generated/resources.ts so the
// translations can be imported anywhere (Node, Next.js, Vite) without file access.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const localesDir = join(root, "locales");
const resources = {};

for (const locale of readdirSync(localesDir).sort()) {
  resources[locale] = {};
  for (const file of readdirSync(join(localesDir, locale)).sort()) {
    if (!file.endsWith(".ftl")) continue;
    resources[locale][file.slice(0, -4)] = readFileSync(
      join(localesDir, locale, file),
      "utf8",
    ).replace(/\r\n/g, "\n");
  }
}

const out = join(root, "src", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "resources.ts"),
  `// Generated by scripts/generate.mjs from locales/**/*.ftl — do not edit.\n` +
    `export const resources = ${JSON.stringify(resources, null, 2)} as const;\n`,
);
